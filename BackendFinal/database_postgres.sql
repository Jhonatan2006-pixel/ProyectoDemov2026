-- ============================================================
--  TaskFlow DB - Script de creacion para PostgreSQL
--  Es la base de datos del servidor de AWS. Tiene la misma
--  estructura que la base local de SQL Server (TaskFlowDB).
--
--  Antes de ejecutarlo (una sola vez) deben existir el usuario
--  con el que se conecta el backend y la base de datos:
--    sudo -u postgres psql -c "CREATE ROLE appuser LOGIN PASSWORD 'la-clave-del-.env'"
--    sudo -u postgres createdb -E UTF8 taskflowdb
--
--  Ejecutar en el servidor:
--    sudo -u postgres psql -d taskflowdb < database_postgres.sql
-- ============================================================

-- Texto que no distingue mayusculas de minusculas. Se usa en el
-- correo para que el inicio de sesion se comporte igual que en
-- SQL Server (Jony@correo.com y jony@correo.com son el mismo).
CREATE EXTENSION IF NOT EXISTS citext;

-- El backend busca las tablas en el esquema "dbo", igual que en SQL Server
CREATE SCHEMA IF NOT EXISTS dbo;

-- 1. Tabla usuarios
CREATE TABLE IF NOT EXISTS dbo.usuarios (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(100)  NOT NULL,
    email       CITEXT        NOT NULL,
    telefono    VARCHAR(20)       NULL,
    password    VARCHAR(255)  NOT NULL,
    created_at  TIMESTAMPTZ       NULL,
    foto        BYTEA             NULL,
    rol         VARCHAR(20)   NOT NULL DEFAULT 'CENSISTA',
    CONSTRAINT PK_usuarios       PRIMARY KEY (id),
    CONSTRAINT UQ_usuarios_email UNIQUE (email),
    CONSTRAINT CK_usuarios_email CHECK (char_length(email) <= 150)
);

-- 2. Tabla censos
CREATE TABLE IF NOT EXISTS dbo.censos (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre                VARCHAR(100)   NOT NULL,
    apellido              VARCHAR(100)   NOT NULL,
    total_miembros        INTEGER        NOT NULL,
    cantidad_televisiones INTEGER        NOT NULL,
    latitud               NUMERIC(10,7)  NOT NULL,
    longitud              NUMERIC(10,7)  NOT NULL,
    tipo_carga            VARCHAR(10)    NOT NULL DEFAULT 'NORMAL',
    usuario_id            INTEGER            NULL,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT PK_censos            PRIMARY KEY (id),
    CONSTRAINT FK_censos_usuario    FOREIGN KEY (usuario_id)
        REFERENCES dbo.usuarios(id),
    CONSTRAINT CK_censos_tipo_carga CHECK (tipo_carga IN ('NORMAL', 'MASIVA'))
);

-- 3. Tabla sesiones_biometricas
--    Cada intento de login biometrico: su UUID, el resultado de
--    Rekognition y si termino en EXITO (onSuccess) o ERROR (onError).
--    tipo ROSTRO = selfie comparada con la foto de perfil
--    tipo VIDA   = prueba de vida (Face Liveness) + comparacion
CREATE TABLE IF NOT EXISTS dbo.sesiones_biometricas (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    session_id  VARCHAR(64)    NOT NULL,
    usuario_id  INTEGER        NOT NULL,
    tipo        VARCHAR(10)    NOT NULL,
    estado      VARCHAR(20)    NOT NULL DEFAULT 'CREADA',
    confianza   NUMERIC(5,2)       NULL,
    similitud   NUMERIC(5,2)       NULL,
    resultado   VARCHAR(10)        NULL,
    mensaje     VARCHAR(255)       NULL,
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ        NULL,
    CONSTRAINT PK_sesiones_biometricas   PRIMARY KEY (id),
    CONSTRAINT UQ_sesiones_session_id    UNIQUE (session_id),
    CONSTRAINT FK_sesiones_usuario       FOREIGN KEY (usuario_id)
        REFERENCES dbo.usuarios(id),
    CONSTRAINT CK_sesiones_tipo          CHECK (tipo IN ('ROSTRO', 'VIDA')),
    CONSTRAINT CK_sesiones_resultado     CHECK (resultado IN ('EXITO', 'ERROR'))
);

-- 4. Permisos del usuario del backend (DB_USER en el archivo .env).
--    Puede leer y modificar los datos, pero no borrar ni cambiar las tablas.
GRANT USAGE ON SCHEMA dbo TO appuser;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON dbo.usuarios, dbo.censos, dbo.sesiones_biometricas TO appuser;
